#!/usr/bin/env bash
# Regenerate docs/src/content/docs/keys.md from the key tables in the code. Needs ./mtx built.
set -euo pipefail
cd "$(dirname "$0")/../.."
{
    printf -- '---\ntitle: Keys\ndescription: Every key and command. Generated from the code.\n---\n\nGenerated by `mtx keys`. Do not edit.\n'
    ./mtx keys
} > docs/src/content/docs/keys.md
